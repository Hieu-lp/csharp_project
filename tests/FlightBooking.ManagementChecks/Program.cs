using System.Collections;
using FlightBooking.BUS;
using FlightBooking.DTO;

int checks=0;
void Check(bool yes,string label){if(!yes)throw new Exception("FAIL: "+label);checks++;Console.WriteLine("PASS: "+label);}
void Reject(Action action,string label){try{action();}catch(ManagementException){Check(true,label);return;}throw new Exception("FAIL: "+label);}
Check(ManagementBUS.ValidateAirport(new(0," Airport "," City ")).AirportName=="Airport","trim airport");
Reject(()=>ManagementBUS.ValidateAirport(new(0," ","City")),"empty airport");
Reject(()=>ManagementBUS.ValidateAirport(new(0,new string('x',151),"City")),"airport maximum length");
var edit=new FlightEdit(0,1,2,120,new(2026,12,31),new(23,0),new(2027,1,1),new(1,0),"SCHEDULED");
ManagementBUS.ValidateFlight(edit);Check(true,"overnight across year");
ManagementBUS.ValidateFlight(edit with{DepartureDate=new(2020,1,1),ArrivalDate=new(2020,1,2)});Check(true,"historical flight allowed");
Reject(()=>ManagementBUS.ValidateFlight(edit with{ArrivalAirportId=1}),"same airport");
Reject(()=>ManagementBUS.ValidateFlight(edit with{TotalSeats=0}),"nonpositive seats");
Reject(()=>ManagementBUS.ValidateFlight(edit with{ArrivalDate=edit.DepartureDate,ArrivalTime=edit.DepartureTime}),"arrival equal departure");
Reject(()=>ManagementBUS.ValidateFlight(edit with{Status="PENDING"}),"unknown status");
var flight=new FlightDTO(1,1,2,"A","B","Airport A","Airport B",edit.DepartureDate,edit.DepartureTime,edit.ArrivalDate,edit.ArrivalTime,120,119,"SCHEDULED");
var old=new FlightManagementDTO(flight,1,100);
var modifying=edit with{FlightId=1};
ManagementBUS.ValidateFlightChange(modifying with{TotalSeats=130},old,true,["20F"]);Check(true,"increase seats preserves allocated positions");
Reject(()=>ManagementBUS.ValidateFlightChange(modifying with{TotalSeats=100},old,true,["20F"]),"cannot remove occupied high seat even with only one ticket");
Reject(()=>ManagementBUS.ValidateFlightChange(modifying with{TotalSeats=100},old,true,["CUSTOM-SEAT"]),"unknown seat mapping prevents shrink");
Reject(()=>ManagementBUS.ValidateFlightChange(modifying with{Status="CANCELLED"},old,true,["1A"]),"cannot cancel booked flight");
Reject(()=>ManagementBUS.ValidateFlightChange(modifying with{DepartureDate=edit.DepartureDate.AddDays(1)},old,true,["1A"]),"cannot reschedule booked flight");
Reject(()=>ManagementBUS.ValidateFlightChange(modifying,old,true,[]),"sold count must equal active tickets");
Check(ManagementBUS.ValidateFare(new(0,1," Economy ",1000,7)).ClassName=="Economy","trim fare");
Reject(()=>ManagementBUS.ValidateFare(new(0,1,"Economy",-1,7)),"negative price");
Reject(()=>ManagementBUS.ValidateFare(new(0,1,"Economy",1.001m,7)),"price precision");
Reject(()=>ManagementBUS.ValidateFare(new(0,1,"Economy",1,-1)),"negative baggage");
var rows=new ArrayList{new AirportDTO(1,"Noi Bai","Ha Noi"),new AirportDTO(2,"Da Nang","Da Nang")};
Check(ManagementSearch.Filter(rows,[new("Tên","chứa","noi"),new("Mã",">=","1")]).Count==1,"ArrayList AND");
Check(ManagementSearch.Filter(rows,[new("Tên","chứa","noi"),new("Mã","=","2")],"OR").Count==2,"ArrayList OR");
Check(ManagementSearch.Filter(rows,[new("Mã","=","1")],not:true).Count==1,"ArrayList NOT");
foreach(var (op,count) in new[]{("=",1),("<>",1),(">",1),(">=",2),("<",0),("<=",1)})Check(ManagementSearch.Filter(rows,[new("Mã",op,"1")]).Count==count,"comparison "+op);
Check(ManagementSearch.Filter(new(){new FlightManagementDTO(flight,1,100)},[new("Ngày đến","=","01/01/2027")]).Count==1,"date predicate");
Check(ManagementSearch.Filter(new(){new FareClassDTO(1,1,"Eco",1000000,7)},[new("Giá",">=","1.000.000")]).Count==1,"Vietnamese money predicate");
Reject(()=>ManagementSearch.Filter(rows,[new("Mã","=","not a number")]),"invalid filter number");
var editor = new FlightBooking.WinForms.EditorSession();
editor.Begin(FlightBooking.WinForms.EditorMode.View,"saved");
Check(!editor.IsDirty("changed")&&!editor.CanSave("changed"),"view mode never edits or saves");
editor.Begin(FlightBooking.WinForms.EditorMode.New,"defaults");
Check(!editor.IsDirty("defaults")&&editor.CanSave("defaults"),"opening new form alone is clean but save validates defaults");
Check(editor.IsDirty("typed"),"new typed data requires discard confirmation");
editor.Begin(FlightBooking.WinForms.EditorMode.Edit,"saved");
Check(!editor.CanSave("saved")&&editor.CanSave("changed"),"edit save enabled only for actual changes");
Check(!editor.IsDirty("saved"),"undoing typing does not prompt to discard");
editor.Begin(FlightBooking.WinForms.EditorMode.View,"committed");
Check(!editor.IsDirty("committed")&&!editor.CanSave("committed"),"successful save or cancel returns clean view");
if(args.Contains("--sql"))SqlManagementChecks.Run(Check,Reject);
Console.WriteLine($"{checks} checks passed.");
