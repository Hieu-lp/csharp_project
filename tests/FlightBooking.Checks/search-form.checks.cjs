const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const controls = new Map();
function control(value = '') { return { value, hidden: false, disabled: false, required: false, handlers: {}, addEventListener(type, handler) { this.handlers[type] = handler; }, setCustomValidity(message) { this.error = message; } }; }
for (const name of ['Search_DepartureAirportId','Search_ArrivalAirportId','swap-airports','Search_DepartureDate','Search_ReturnDate','return-date-field','swap-feedback']) controls.set(name, control());
controls.get('Search_DepartureDate').value = '2026-12-15';
controls.get('Search_ReturnDate').value = '2026-12-16';
const trip = control('OneWay');
const document = {getElementById: id => controls.get(id), querySelector: () => trip, querySelectorAll: () => [trip]};
vm.runInNewContext(fs.readFileSync('src/FlightBooking.Web/wwwroot/js/search.js','utf8'), {document});
const date = controls.get('Search_ReturnDate');
assert(date.disabled && !date.required && controls.get('return-date-field').hidden && date.value === '');
trip.value = 'RoundTrip'; trip.handlers.change();
assert(!date.disabled && date.required && !controls.get('return-date-field').hidden);
date.value = '2026-12-14'; date.handlers.change(); assert(date.error);
date.value = '2026-12-15'; date.handlers.change(); assert.equal(date.error,'');
trip.value='OneWay'; trip.handlers.change(); assert.equal(date.value,''); assert(date.disabled && !date.required);
controls.get('Search_DepartureAirportId').value='1'; controls.get('Search_ArrivalAirportId').value='2';
controls.get('swap-airports').handlers.click(); assert.equal(controls.get('Search_DepartureAirportId').value,'2');
console.log('PASS: real search.js toggles return date, required/disabled state, invalid date, cleared one-way value and airport swap.');
let submitted = 0;
controls.set('flight-search', { dataset: { selectedFlight: 'true' }, requestSubmit() { submitted++; } });
controls.set('Search_Passengers', control('3'));
controls.get('Search_DepartureAirportId').disabled = true;
vm.runInNewContext(fs.readFileSync('src/FlightBooking.Web/wwwroot/js/search.js','utf8'), {document});
controls.get('Search_Passengers').handlers.change();
assert.equal(submitted, 1);
assert.equal(controls.get('swap-airports').hidden, true);
console.log('PASS: selected deal auto-submits quantity changes and hides airport swap.');
